export default async (req: Request) => {
  const url = new URL(req.url);
  const run = url.searchParams.get("run") === "1";

  const { db } = await import("../../db");
  const schema = await import("../../db/schema");
  const { and, eq, inArray } = await import("drizzle-orm");

  /* ---------- 진단 ---------- */
  if (!run) {
    try {
      const slugs = [...PAGES.map((p) => p.slug), ...NEW_PAGES.map((p) => p.slug), "home-intro"];
      const rows = await db
        .select({
          slug: schema.sitePages.slug,
          status: schema.sitePages.status,
          body: schema.sitePages.contentHtml,
        })
        .from(schema.sitePages)
        .where(inArray(schema.sitePages.slug, slugs));
      const cur = rows.map((r: any) => ({
        slug: r.slug,
        status: r.status,
        본문글자: String(r.body || "").length,
      }));
      const missing = slugs.filter((s) => !rows.some((r: any) => r.slug === s));
      return json({ ok: true, mode: "진단", 현재: cur, 없는페이지: missing, 실행: "?run=1 (어드민 로그인 필요)" });
    } catch (e: any) {
      return json({ ok: false, step: "diag", detail: String(e?.message || e).slice(0, 500) }, 500);
    }
  }

  /* ---------- 실행 ---------- */
  const auth = await requireAdmin(req);
  if (!auth.ok) return (auth as { ok: false; res: Response }).res;

  const done: Record<string, any> = {};

  /* ① 홈 미션 소개 */
  try {
    const [exist] = await db
      .select({ id: schema.sitePages.id, body: schema.sitePages.contentHtml })
      .from(schema.sitePages)
      .where(eq(schema.sitePages.slug, "home-intro"))
      .limit(1);
    if (!exist) {
      await db.insert(schema.sitePages).values({
        slug: "home-intro",
        title: "홈 소개",
        subtitle: "홈 화면 가운데에 들어가는 단체 소개 구역입니다.",
        contentHtml: HOME_INTRO,
        status: "published",
        layout: "default",
        seoDescription: "(사)교사유가족협의회 소개 — 홈 화면에 들어가는 구역",
      } as any);
      done["1_홈소개"] = "새로 만듦";
    } else if (String(exist.body || "").length < 500) {
      await db
        .update(schema.sitePages)
        .set({ contentHtml: HOME_INTRO, status: "published", updatedAt: new Date() } as any)
        .where(eq(schema.sitePages.id, exist.id));
      done["1_홈소개"] = "본문 채움";
    } else {
      done["1_홈소개"] = "이미 내용 있음 — 건너뜀";
    }
  } catch (e: any) {
    return json({ ok: false, step: "home_intro", detail: String(e?.message || e).slice(0, 500), stack: String(e?.stack || "").slice(0, 800) }, 500);
  }

  /* ② 기존 페이지 확충 */
  try {
    const result: Record<string, string> = {};
    for (const p of PAGES) {
      const [row] = await db
        .select({ id: schema.sitePages.id, body: schema.sitePages.contentHtml })
        .from(schema.sitePages)
        .where(eq(schema.sitePages.slug, p.slug))
        .limit(1);
      if (!row) { result[p.slug] = "페이지 없음 — 건너뜀"; continue; }
      const curLen = String(row.body || "").length;
      if (curLen >= p.replaceIfShorterThan) { result[p.slug] = `현재 ${curLen}자 — 충분해서 건너뜀`; continue; }
      const set: Record<string, any> = { contentHtml: p.contentHtml, updatedAt: new Date() };
      if (p.title) set.title = p.title;
      if (p.subtitle) set.subtitle = p.subtitle;
      if (p.seoDescription) set.seoDescription = p.seoDescription;
      await db.update(schema.sitePages).set(set as any).where(eq(schema.sitePages.id, row.id));
      result[p.slug] = `${curLen}자 → ${p.contentHtml.length}자`;
    }
    done["2_페이지_확충"] = result;
  } catch (e: any) {
    return json({ ok: false, step: "expand_pages", detail: String(e?.message || e).slice(0, 500), stack: String(e?.stack || "").slice(0, 800) }, 500);
  }

  /* ③ 신규 정보 페이지 */
  try {
    const added: string[] = [];
    for (const p of NEW_PAGES) {
      const [exist] = await db
        .select({ id: schema.sitePages.id })
        .from(schema.sitePages)
        .where(eq(schema.sitePages.slug, p.slug))
        .limit(1);
      if (exist) continue;
      await db.insert(schema.sitePages).values({
        slug: p.slug,
        title: p.title,
        eyebrow: p.eyebrow || null,
        subtitle: p.subtitle || null,
        contentHtml: p.contentHtml,
        status: "published",
        layout: "default",
        seoDescription: p.seoDescription,
      } as any);
      added.push(p.slug);
    }
    done["3_신규페이지"] = added;
  } catch (e: any) {
    return json({ ok: false, step: "new_pages", detail: String(e?.message || e).slice(0, 500), stack: String(e?.stack || "").slice(0, 800) }, 500);
  }

  /* ④ 신규 페이지 메뉴 등록 */
  try {
    const [about] = await db
      .select({ id: schema.navMenuItems.id })
      .from(schema.navMenuItems)
      .where(and(eq(schema.navMenuItems.menuLocation, "header"), eq(schema.navMenuItems.label, "협의회 소개")))
      .limit(1);
    const [biz] = await db
      .select({ id: schema.navMenuItems.id })
      .from(schema.navMenuItems)
      .where(and(eq(schema.navMenuItems.menuLocation, "header"), eq(schema.navMenuItems.label, "협의회 사업")))
      .limit(1);
    /* 안내 페이지는 '협의회 사업' 아래, 투명한 운영은 '협의회 소개' 아래 */
    const placement: Record<string, number | null> = {
      "survivor-guide": biz?.id ?? about?.id ?? null,
      "line-of-duty": biz?.id ?? about?.id ?? null,
      "teacher-rights": biz?.id ?? about?.id ?? null,
      transparency: about?.id ?? null,
    };
    const added: string[] = [];
    for (const p of NEW_PAGES) {
      const [exist] = await db
        .select({ id: schema.navMenuItems.id })
        .from(schema.navMenuItems)
        .where(and(eq(schema.navMenuItems.menuLocation, "header"), eq(schema.navMenuItems.href, `/p/${p.slug}`)))
        .limit(1);
      if (exist) continue;
      await db.insert(schema.navMenuItems).values({
        parentId: placement[p.slug] ?? null,
        menuLocation: "header",
        label: p.menuLabel,
        href: `/p/${p.slug}`,
        sortOrder: p.menuSort,
        isActive: true,
      } as any);
      added.push(p.menuLabel);
    }
    done["4_메뉴등록"] = added;
  } catch (e: any) {
    return json({ ok: false, step: "menu", detail: String(e?.message || e).slice(0, 500), stack: String(e?.stack || "").slice(0, 800) }, 500);
  }

  /* ⑤ 자주 묻는 질문 추가 */
  try {
    const added: string[] = [];
    for (const f of FAQS) {
      const [exist] = await db
        .select({ id: schema.faqs.id })
        .from(schema.faqs)
        .where(eq(schema.faqs.question, f.q))
        .limit(1);
      if (exist) continue;
      await db.insert(schema.faqs).values({
        category: f.cat,
        question: f.q,
        answer: f.a,
        isActive: true,
      } as any);
      added.push(f.q.slice(0, 24));
    }
    done["5_FAQ_추가"] = added;
  } catch (e: any) {
    return json({ ok: false, step: "faqs", detail: String(e?.message || e).slice(0, 500), stack: String(e?.stack || "").slice(0, 800) }, 500);
  }

  return json({ ok: true, mode: "실행 완료", 결과: done, 다음: "이 파일을 삭제하고 커밋하세요 (1회용)" });
};
