/** KG 규칙 적용 뒤에도 «후원»이 남았는지(사람이 문장을 직접 봐야 하는 곳) */
export const KG_LEFTOVER_RX = /후원/;

export function convertKgTerms(input: string | null | undefined): string {
  let s = String(input ?? "");
  for (const [re, rep] of KG_TERM_RULES) s = s.replace(re, rep);
  return s;
}

/** 공개 문구 전체 전환 — 옛 «후원하기»류 규칙 → KG 규칙 차례로 */
export function convertPublicTerms(input: string | null | undefined): string {
  return convertKgTerms(convertMemberTerms(input));
}

/** 미리보기용 — 두 규칙 묶음을 차례로 적용하며 바뀐 곳을 기록 */
export function convertPublicTermsTraced(input: string | null | undefined, maxTrace = 12): { out: string; trace: { from: string; to: string; ctx: string }[] } {
  const a = convertMemberTermsTraced(input, maxTrace, MEMBER_TERM_RULES);
  const b = convertMemberTermsTraced(a.out, maxTrace, KG_TERM_RULES);
  return { out: b.out, trace: [...a.trace, ...b.trace].slice(0, maxTrace) };
}
