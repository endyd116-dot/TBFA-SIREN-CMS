/** 옛 용어 탐지(변경 필요 여부 판단용) */
export const MEMBER_TERM_RX = /후원하기|후원 동참|후원 금액|후원금|후원 내역|후원 회원|정기 후원(?!회원)|일시 후원(?!회원)|정기후원|일시후원|후원하러|후원 계속/;

export function convertMemberTerms(input: string | null | undefined): string {
  let s = String(input ?? "");
  for (const [re, rep] of MEMBER_TERM_RULES) s = s.replace(re, rep);
  return s;
}

/** 미리보기용 — 규칙이 실제로 어디를 어떻게 바꾸는지 앞뒤 40자 문맥과 함께 기록(태그 제거) */
export function convertMemberTermsTraced(input: string | null | undefined, maxTrace = 8, rules: [RegExp, string][] = MEMBER_TERM_RULES): { out: string; trace: { from: string; to: string; ctx: string }[] } {
  let s = String(input ?? "");
  const trace: { from: string; to: string; ctx: string }[] = [];
  for (const [re, rep] of rules) {
    const rx = new RegExp(re.source, re.flags);
    let m: RegExpExecArray | null;
    while ((m = rx.exec(s))) {
      if (trace.length < maxTrace) {
        const ctx = s.slice(Math.max(0, m.index - 40), m.index + m[0].length + 40).replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
        trace.push({ from: m[0], to: rep, ctx });
      }
      if (!m[0].length) rx.lastIndex++;
    }
    s = s.replace(re, rep);
  }
  return { out: s, trace };
}

